#!/usr/bin/env python3
"""Run Census.lean and check its output against statements/.

  census.py           compare with statements/INVENTORY.md, statements/CERTIFICATES.md and
                      statements/RAW.sha256
  census.py --write   write those three files from the census (after a reviewed change)

Checks: the census imports every proof module of the package; no package module declares an
axiom or an opaque constant; every theorem (auxiliary ones included) depends on a subset of
`propext`, `Classical.choice` and `Quot.sound`; no type holds a syntax value; and the
non-auxiliary theorems are exactly those of the two lists, with the same printed statement and
the same SHA-256 of the raw type. CERTIFICATES.md holds the theorems of the lookup-certificate
leaves (modules `*.LeafN`); INVENTORY.md holds all the others.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
INV = PKG / 'statements' / 'INVENTORY.md'
CERT = PKG / 'statements' / 'CERTIFICATES.md'
RAW = PKG / 'statements' / 'RAW.sha256'
ALLOWED = {'propext', 'Classical.choice', 'Quot.sound'}
GROUPS = ['Semantics', 'Exec', 'Poseidon', 'Determinism', 'Deposit', 'Withdraw', 'Transfer', 'Merkle']
FLAGS = ['-M8192', '--tstack=65536', '-DElab.async=false', '-DmaxRecDepth=10000',
         '-DmaxHeartbeats=4000000']
HEADER = """# {title}
# Generated by scripts/census.py --write from the census (Census.lean); checked by scripts/check.sh.
# Format (one per line): <fully qualified name> :: <statement as Lean prints it; line breaks of the
# printer, with their indentation, become one space>
# {scope}
# Grouped by module. Auxiliary theorems (internal or private names) are left out; the census
# still checks their axioms. statements/RAW.sha256 pins the SHA-256 of the raw form of each type.
"""


def package_modules():
    out = set()
    for f in PKG.rglob('*.lean'):
        rel = f.relative_to(PKG)
        if rel.parts[0] in GROUPS or rel.name == 'Determinism.lean':
            out.add('.'.join(rel.with_suffix('').parts))
    return out


def main():
    write = sys.argv[1:] == ['--write']
    p = subprocess.run(['lake', 'env', 'lean', *FLAGS, 'Census.lean'], cwd=PKG,
                       capture_output=True, text=True)
    if p.returncode != 0:
        print(p.stdout[-3000:], p.stderr[-3000:])
        sys.exit('CENSUS FAIL: Census.lean did not run')
    rows = [json.loads(l) for l in p.stdout.splitlines() if l.startswith('{')]
    bad = []
    seen = {r['module'] for r in rows if r['kind'] == 'module'}
    missing = package_modules() - seen
    if missing:
        bad.append(f'modules not imported by the census: {sorted(missing)[:5]} ({len(missing)})')
    thms = [r for r in rows if r['kind'] == 'theorem']
    for r in rows:
        if r['kind'] in ('axiomInfo', 'opaqueInfo'):
            bad.append(f"{r['kind']} {r['name']} in {r['module']}")
    nonstd = [(r['name'], r['axioms']) for r in thms if set(r['axioms']) - ALLOWED]
    for n, a in nonstd:
        bad.append(f'axioms of {n}: {a}')
    for r in thms:
        if '(dsyntax)' in r['raw']:
            bad.append(f"syntax value in the type of {r['name']}")
        if '⋯' in r['type']:
            bad.append(f"elided statement of {r['name']}")
    public = sorted((r for r in thms if not r['internal']), key=lambda r: (r['module'], r['name']))
    leaf = lambda r: r['module'].split('.')[-1].startswith('Leaf') and r['module'].split('.')[-1][4:].isdigit()
    files = [(INV, 'Inventory of the theorems of circuits-lampe',
              'The lookup-certificate leaves are in statements/CERTIFICATES.md.', False),
             (CERT, 'Theorems of the lookup-certificate leaves of circuits-lampe',
              'Only the leaf modules (`*.LeafN`); the other theorems are in statements/INVENTORY.md.', True)]
    texts = {}
    for path, title, scope, want_leaf in files:
        lines, mod = [], None
        for r in public:
            if leaf(r) != want_leaf:
                continue
            if r['module'] != mod:
                mod = r['module']
                lines.append(f'# {mod}')
            flat = ' '.join(x.strip() for x in r['type'].splitlines())
            lines.append(f"{r['name']} :: {flat}")
        texts[path] = HEADER.format(title=title, scope=scope) + '\n'.join(lines) + '\n'
    raw_lines = [f"{hashlib.sha256(r['raw'].encode()).hexdigest()}  {r['name']}" for r in public]
    raw_text = '\n'.join(sorted(raw_lines, key=lambda l: l.split()[1])) + '\n'
    texts[RAW] = raw_text
    ninv = sum(1 for r in public if not leaf(r))
    if write:
        INV.parent.mkdir(exist_ok=True)
        for path, text in texts.items():
            path.write_text(text)
        print(f'wrote {INV.name} ({ninv}), {CERT.name} ({len(public) - ninv}) and {RAW.name} ({len(public)})')
    else:
        def entries(text, sep):
            d = {}
            for l in text.splitlines():
                if l and not l.startswith('#'):
                    a, b = (l.split(sep, 1) if sep == ' :: ' else reversed(l.split('  ', 1)))
                    if a in d:
                        bad.append(f'duplicate entry {a}')
                    d[a] = b
            return d
        for path in (INV, CERT, RAW):
            sep = '  ' if path == RAW else ' :: '
            want, got = entries(path.read_text(), sep), entries(texts[path], sep)
            for n in sorted(want.keys() - got.keys()):
                bad.append(f'{path.name}: missing theorem {n}')
            for n in sorted(got.keys() - want.keys()):
                bad.append(f'{path.name}: theorem not listed: {n}')
            for n in sorted(want.keys() & got.keys()):
                if want[n] != got[n]:
                    bad.append(f'{path.name}: entry of {n} differs')
    nax = sum(1 for r in thms if r['axioms'])
    if bad:
        for b in bad[:40]:
            print('CENSUS', b)
        print(f'CENSUS FAIL: {len(bad)} problems')
        sys.exit(1)
    print(f'CENSUS PASS: {len(seen)} modules, {len(thms)} theorems ({ninv} in the inventory, '
          f'{len(public) - ninv} in the certificate list), '
          f'{nax} with axioms, all within {sorted(ALLOWED)}')


if __name__ == '__main__':
    main()
