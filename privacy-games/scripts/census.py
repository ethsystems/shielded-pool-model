#!/usr/bin/env python3
"""Run Census.lean and check its output against statements/.

  census.py                     run the census, keep its output in build/census.jsonl and
                                compare with statements/INVENTORY.md and statements/RAW.sha256
  census.py --write             write those two files from the census (after a reviewed change)
  census.py --from FILE --statements DIR
                                compare a kept census output with DIR/INVENTORY.md and
                                DIR/RAW.sha256, without running Lean (the controls use this)

Checks: the census imports every game module of the package; no package or model module
declares an axiom or an opaque constant; every theorem (auxiliary ones included) depends on a
subset of `propext`, `Classical.choice` and `Quot.sound`; no type holds a syntax value or an
elided term; and the non-auxiliary theorems of the package are exactly those of
INVENTORY.md, with the same printed statement and the same SHA-256 of the raw type.

Counts: modules; declarations written in the source (a `def`, `abbrev`, `theorem`, `lemma`,
`structure`, `inductive` or named `instance`; not constructors, projections or names that
Lean generates); theorems written in the source; all theorems, auxiliary ones included; and
the same for the three model modules.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
STATEMENTS = PKG / 'statements'
KEPT = PKG / 'build' / 'census.jsonl'
ALLOWED = {'propext', 'Classical.choice', 'Quot.sound'}
GROUPS = ['PoolGame', 'GameCorrespondence', 'RecipientGame', 'ChainGame', 'ChosenWorldGame',
          'WithdrawGame', 'OwnerGame', 'SenderGame', 'PrivacyTools', 'CommitROM']
HEADER = """# Inventory of the theorems of privacy-games
# Generated by scripts/census.py --write from the census (Census.lean); checked by scripts/check.sh.
# Format (one per line): <fully qualified name> :: <statement as Lean prints it; line breaks of the
# printer, with their indentation, become one space>
# Grouped by module. Auxiliary theorems (internal or private names) are left out; the census
# still checks their axioms. statements/RAW.sha256 pins the SHA-256 of the raw form of each type.
"""


def package_modules():
    out = set()
    for g in GROUPS:
        files = list((PKG / g).rglob('*.lean')) + [PKG / f'{g}.lean']
        for f in files:
            if f.exists():
                out.add('.'.join(f.relative_to(PKG).with_suffix('').parts))
    return out


def run_census():
    p = subprocess.run(['lake', 'env', 'lean', 'Census.lean'], cwd=PKG,
                       capture_output=True, text=True)
    if p.returncode != 0:
        print(p.stdout[-3000:], p.stderr[-3000:])
        sys.exit('CENSUS FAIL: Census.lean did not run')
    lines = [l for l in p.stdout.splitlines() if l.startswith('{')]
    KEPT.parent.mkdir(exist_ok=True)
    KEPT.write_text('\n'.join(lines) + '\n')
    return lines


def render(public):
    lines, mod = [], None
    for r in public:
        if r['module'] != mod:
            mod = r['module']
            lines.append(f'# {mod}')
        flat = ' '.join(x.strip() for x in r['type'].splitlines())
        lines.append(f"{r['name']} :: {flat}")
    inv = HEADER + '\n'.join(lines) + '\n'
    raw = [f"{hashlib.sha256(r['raw'].encode()).hexdigest()}  {r['name']}" for r in public]
    return inv, '\n'.join(sorted(raw, key=lambda l: l.split()[1])) + '\n'


def entries(text, sep, bad, label):
    d = {}
    for l in text.splitlines():
        if l and not l.startswith('#'):
            if sep == ' :: ':
                a, b = l.split(sep, 1)
            else:
                b, a = l.split(sep, 1)
            if a in d:
                bad.append(f'{label}: duplicate entry {a}')
            d[a] = b
    return d


def main():
    args = sys.argv[1:]
    write = args == ['--write']
    statements = STATEMENTS
    if args[:1] == ['--from']:
        lines = Path(args[1]).read_text().splitlines()
        statements = Path(args[3]) if args[2:3] == ['--statements'] else STATEMENTS
    else:
        lines = run_census()
    rows = [json.loads(l) for l in lines]
    bad = []
    seen = {r['module'] for r in rows if r['kind'] == 'module'}
    missing = package_modules() - seen
    if missing:
        bad.append(f'modules not imported by the census: {sorted(missing)[:5]} ({len(missing)})')
    consts = [r for r in rows if r['kind'] != 'module']
    for r in consts:
        if r['kind'] in ('axiomInfo', 'opaqueInfo'):
            bad.append(f"{r['kind']} {r['name']} in {r['module']}")
    thms = [r for r in consts if r['kind'] == 'theorem']
    for r in thms:
        if set(r['axioms']) - ALLOWED:
            bad.append(f"axioms of {r['name']}: {r['axioms']}")
        if '(dsyntax)' in r['raw']:
            bad.append(f"syntax value in the type of {r['name']}")
        if '⋯' in r['type']:
            bad.append(f"elided statement of {r['name']}")
    pkg = [r for r in consts if r['group'] == 'package']
    mdl = [r for r in consts if r['group'] == 'model']
    public = sorted((r for r in pkg if r['kind'] == 'theorem' and not r['internal']),
                    key=lambda r: (r['module'], r['name']))
    inv_text, raw_text = render(public)
    if write:
        STATEMENTS.mkdir(exist_ok=True)
        (STATEMENTS / 'INVENTORY.md').write_text(inv_text)
        (STATEMENTS / 'RAW.sha256').write_text(raw_text)
        print(f'wrote INVENTORY.md and RAW.sha256 ({len(public)} theorems)')
    else:
        for name, sep, got in (('INVENTORY.md', ' :: ', inv_text), ('RAW.sha256', '  ', raw_text)):
            path = statements / name
            if not path.exists():
                bad.append(f'{name}: missing')
                continue
            want = entries(path.read_text(), sep, bad, name)
            have = entries(got, sep, bad, name)
            for n in sorted(want.keys() - have.keys()):
                bad.append(f'{name}: missing theorem {n}')
            for n in sorted(have.keys() - want.keys()):
                bad.append(f'{name}: theorem not listed: {n}')
            for n in sorted(want.keys() & have.keys()):
                if want[n] != have[n]:
                    bad.append(f'{name}: entry of {n} differs')
    if bad:
        for b in bad[:40]:
            print('CENSUS', b)
        print(f'CENSUS FAIL: {len(bad)} problems')
        sys.exit(1)
    src = [r for r in pkg if r['source']]
    src_thm = [r for r in src if r['kind'] == 'theorem']
    pkg_thm = [r for r in pkg if r['kind'] == 'theorem']
    msrc = [r for r in mdl if r['source']]
    mthm = [r for r in mdl if r['kind'] == 'theorem']
    nax = sum(1 for r in thms if r['axioms'])
    print(f'CENSUS COUNTS package: {len(seen)} modules, {len(src)} declarations written in the '
          f'source, {len(src_thm)} of them theorems; {len(pkg)} constants, {len(pkg_thm)} '
          f'theorems with auxiliary ones, {len(public)} in the inventory')
    print(f'CENSUS COUNTS model: 3 modules, {len(msrc)} declarations written in the source, '
          f'{len(mthm)} theorems')
    print(f'CENSUS PASS: {len(seen)} modules, {len(src)} declarations, {len(src_thm)} theorems '
          f'written ({len(pkg_thm)} with auxiliary ones, {len(public)} in the inventory); '
          f'{nax} theorems use axioms, all within {sorted(ALLOWED)}')


if __name__ == '__main__':
    main()
