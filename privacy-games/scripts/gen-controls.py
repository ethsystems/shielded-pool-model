#!/usr/bin/env python3
"""Generate the Lean controls of controls/ from the game modules.

  gen-controls.py          write controls/<name>.lean and controls/same_<name>.lean
  gen-controls.py --check  compare with the files in controls/ (scripts/check.sh runs this)

Each Lean control is a copy of one game module, cut after one headline theorem, with one
change to that theorem's statement and none to its proof. The proof must then fail
(scripts/controls.py). The `same_` copy is the same cut with no change; it must compile, so
that the failure of the changed copy comes from the change. The eight theorems are the
headline theorems of the eight modules that the planted cases of the earlier replay altered.
"""
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
CONTROLS = PKG / 'controls'

# name, module file, theorem, old text of the statement, new text
CASES = [
    ('recipient_hiding_halved', 'RecipientGame/Basic.lean', 'advantage_le',
     'advantage sup setup adv ≤ 2 * n * H.primitives.εHiding +',
     'advantage sup setup adv ≤ n * H.primitives.εHiding +'),
    ('withdraw_rejection_quartered', 'WithdrawGame/Transport.lean', 'advantage_le',
     'advantage sup adv ≤ ε + rejectionProbability sup adv / 2 := by',
     'advantage sup adv ≤ ε + rejectionProbability sup adv / 4 := by'),
    ('sender_hiding_dropped', 'SenderGame/Transport.lean', 'advantage_le',
     'advantage sup adv ≤ η + ε + rejectionProbability sup adv / 2 := by',
     'advantage sup adv ≤ η + rejectionProbability sup adv / 2 := by'),
    ('withdraw_rom_birthday_dropped', 'WithdrawGame/ROM/Kernel.lean', 'switch_bound',
     '(Fintype.card ι : ℝ) * q / Fintype.card P.SpendKey +\n'
     '      (Fintype.card ι : ℝ) * (Fintype.card ι - 1) / Fintype.card P.SpendKey := by',
     '(Fintype.card ι : ℝ) * q / Fintype.card P.SpendKey := by'),
    ('sender_rom_salt_term_minus_one', 'SenderGame/ROMCommit/Security.lean', 'advantage_le_queryBound',
     '(2*(qc+6*L+4+qg)+1 : ℝ)', '(2*(qc+6*L+4+qg) : ℝ)'),
    ('recipient_rom_query_term_halved', 'RecipientGame/ROMCommit/Security.lean', 'advantage_le_queryBound',
     '(2*n : ℝ) * (qc+qg+4*setup.length+6*n)', '(n : ℝ) * (qc+qg+4*setup.length+6*n)'),
    ('chain_commit_only_setup_dropped', 'ChainGame/CommitOnly/Security.lean', 'advantage_le_queryBound',
     '(qc+qg+4*setup.length+6*n)', '(qc+qg+6*n)'),
    ('chain_rom_collisions_rejection_quartered', 'ChainGame/CommitOnly/CollisionRejection.lean',
     'advantage_le_rom_collisions',
     '(Fintype.card P.Salt) (Fintype.card P.Salt))/2 := by',
     '(Fintype.card P.Salt) (Fintype.card P.Salt))/4 := by'),
]


def cut(text, theorem):
    """The module text up to the end of `theorem`: the theorem runs to the first later line
    that is not blank and not indented."""
    lines = text.split('\n')
    start = next(i for i, l in enumerate(lines) if l.startswith(f'theorem {theorem} '))
    end = start + 1
    while end < len(lines) and (not lines[end].strip() or lines[end][0] in ' \t'):
        end += 1
    while not lines[end - 1].strip():
        end -= 1
    return '\n'.join(lines[:end]) + '\n', '\n'.join(lines[start:end])


def files():
    out = {}
    for name, module, theorem, old, new in CASES:
        text, thm = cut((PKG / module).read_text(), theorem)
        stmt = thm.split(':= by')[0] + ':= by'
        assert stmt.count(old) == 1, (name, old)
        changed = text.replace(thm, thm.replace(stmt, stmt.replace(old, new)))
        assert changed != text
        mod = module[:-5].replace('/', '.')
        head = (f'-- Control {name} (generated by scripts/gen-controls.py): {mod} cut after '
                f'`{theorem}`,\n-- with one change to its statement. It must fail.\n')
        same = (f'-- Control same_{name} (generated by scripts/gen-controls.py): {mod} cut after '
                f'`{theorem}`,\n-- unchanged. It must compile.\n')
        out[f'{name}.lean'] = head + changed
        out[f'same_{name}.lean'] = same + text
    return out


def main():
    want = files()
    if sys.argv[1:] == ['--check']:
        bad = [n for n, t in want.items() if not (CONTROLS / n).exists() or (CONTROLS / n).read_text() != t]
        have = {p.name for p in CONTROLS.glob('*.lean')}
        bad += sorted(have - want.keys())
        if bad:
            print(f'GEN-CONTROLS FAIL: {bad}')
            sys.exit(1)
        print(f'gen-controls: the {len(want)} Lean controls equal the generator output')
        return
    CONTROLS.mkdir(exist_ok=True)
    for n, t in want.items():
        (CONTROLS / n).write_text(t)
    print(f'wrote {len(want)} Lean controls')


if __name__ == '__main__':
    main()
