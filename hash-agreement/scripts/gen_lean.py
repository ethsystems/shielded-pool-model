CORE = f"""-- CORE
abbrev F : ℕ := {c.F}
abbrev K := ZMod F
abbrev St := K × K × K

structure M3 where
  a00 : K
  a01 : K
  a02 : K
  a10 : K
  a11 : K
  a12 : K
  a20 : K
  a21 : K
  a22 : K
  deriving DecidableEq

/-- row vector times matrix: out_i = sum_j s_j * m[j][i] -/
def vm (s : St) (m : M3) : St :=
  (s.1 * m.a00 + s.2.1 * m.a10 + s.2.2 * m.a20,
   s.1 * m.a01 + s.2.1 * m.a11 + s.2.2 * m.a21,
   s.1 * m.a02 + s.2.1 * m.a12 + s.2.2 * m.a22)

def mm (a b : M3) : M3 :=
  ⟨a.a00 * b.a00 + a.a01 * b.a10 + a.a02 * b.a20,
   a.a00 * b.a01 + a.a01 * b.a11 + a.a02 * b.a21,
   a.a00 * b.a02 + a.a01 * b.a12 + a.a02 * b.a22,
   a.a10 * b.a00 + a.a11 * b.a10 + a.a12 * b.a20,
   a.a10 * b.a01 + a.a11 * b.a11 + a.a12 * b.a21,
   a.a10 * b.a02 + a.a11 * b.a12 + a.a12 * b.a22,
   a.a20 * b.a00 + a.a21 * b.a10 + a.a22 * b.a20,
   a.a20 * b.a01 + a.a21 * b.a11 + a.a22 * b.a21,
   a.a20 * b.a02 + a.a21 * b.a12 + a.a22 * b.a22⟩

def aff (T : M3) (v x : St) : St := vm x T + v

def I3 : M3 := ⟨1, 0, 0, 0, 1, 0, 0, 0, 1⟩
"""


def plain_block(C, M):
    return f"""-- PLAIN: textbook Poseidon, t = 3, RF = 8, RP = 57, x^5.
-- Constants and M from inputs/sol_params.json (the hash-differential extraction from
-- PoseidonT3.sol, see inputs/PROVENANCE.md), 195 constants, canonical sha256
-- {c.PLAIN_RC_SHA}. The Solidity round lemmas re-check every value against the Yul literals.
def plainCL : List K :=
  {klist(C)}

def plainC (j : ℕ) : St := (plainCL.getD (3 * j) 0, plainCL.getD (3 * j + 1) 0, plainCL.getD (3 * j + 2) 0)

def plainM : M3 := {m3(M)}

/-- textbook mix, row-vector convention out_i = sum_j s_j * M[j][i] -/
def pmix (m : M3) (s : St) : St :=
  (s.1 * m.a00 + s.2.1 * m.a10 + s.2.2 * m.a20,
   s.1 * m.a01 + s.2.1 * m.a11 + s.2.2 * m.a21,
   s.1 * m.a02 + s.2.1 * m.a12 + s.2.2 * m.a22)

def sboxAll (s : St) : St := (s.1 ^ 5, s.2.1 ^ 5, s.2.2 ^ 5)
def sbox0 (s : St) : St := (s.1 ^ 5, s.2.1, s.2.2)

/-- plain round j: add round constant, S-box (all words in the 4 + 4 full rounds, word 0 in
the 57 partial rounds), mix. -/
def plainRound (j : ℕ) (s : St) : St :=
  pmix plainM (if j < 4 ∨ 61 ≤ j then sboxAll (s + plainC j) else sbox0 (s + plainC j))

def plainPerm (s : St) : St := (List.range 65).foldl (fun s j => plainRound j s) s

def plainHash2 (a b : K) : K := (plainPerm (0, a, b)).1
"""


def noir_block(rc, mds, pre, sp):
    return f"""-- NOIR: noir-lang/poseidon v0.3.0 (0880c371), tables parsed from src/poseidon/bn254/consts.nr
-- x5_3_config() (sha256 {c.NOIR_SHA['bn254/consts.nr']}); control transcribed by hand
-- from src/poseidon/mod.nr permute (lines 49-110), apply_matrix (113-123), sigma (156-165),
-- and src/poseidon/bn254.nr hash_internal (14-23) / hash_2 (33-35). Field = ZMod F; pow_32(alpha)
-- with alpha() = 5 is read as ^ 5; std::as_witness has no value effect.
def noirRCL : List K :=
  {klist(rc)}

def rc (i : ℕ) : K := noirRCL.getD i 0

def noirSL : List K :=
  {klist(sp)}

def sp (i : ℕ) : K := noirSL.getD i 0

def noirM : M3 := {m3(mds)}
def noirP : M3 := {m3(pre)}

-- apply_matrix: out[i] += vec[j] * matrix[j][i], j = 0..2, out starts at 0
def applyMatrix (m : M3) (v : St) : St :=
  (((0 + v.1 * m.a00) + v.2.1 * m.a10) + v.2.2 * m.a20,
   ((0 + v.1 * m.a01) + v.2.1 * m.a11) + v.2.2 * m.a21,
   ((0 + v.1 * m.a02) + v.2.1 * m.a12) + v.2.2 * m.a22)

-- sigma: t = y[i]; tt = t * t; tttt = tt * tt; y[i] *= tttt
def sigma (s : St) : St :=
  (s.1 * ((s.1 * s.1) * (s.1 * s.1)),
   s.2.1 * ((s.2.1 * s.2.1) * (s.2.1 * s.2.1)),
   s.2.2 * ((s.2.2 * s.2.2) * (s.2.2 * s.2.2)))

-- for i in 0..T: state[i] += C[i]
def addC (s C : St) : St := (s.1 + C.1, s.2.1 + C.2.1, s.2.2 + C.2.2)

def rc3 (b : ℕ) : St := (rc b, rc (b + 1), rc (b + 2))

-- one partial-round body: state[0] = pow; state[0] += k; newState0 = sum_j sparse[j] * state[j];
-- state[k] += state[0] * sparse[T + k - 1] (state[0] is the updated word 0); state[0] = newState0
def partialBody (k s0 s1 s2 s3 s4 : K) (s : St) : St :=
  let a := s.1 ^ 5 + k
  (((0 + s0 * a) + s1 * s.2.1) + s2 * s.2.2, s.2.1 + a * s3, s.2.2 + a * s4)

def partialStep (s : St) (r : ℕ) : St :=
  partialBody (rc ((8 / 2 + 1) * 3 + r))
    (sp ((3 * 2 - 1) * r + 0)) (sp ((3 * 2 - 1) * r + 1)) (sp ((3 * 2 - 1) * r + 2))
    (sp ((3 * 2 - 1) * r + 3 + 1 - 1)) (sp ((3 * 2 - 1) * r + 3 + 2 - 1)) s

def noirPermute (s : St) : St :=
  let s := addC s (rc3 0)
  let s := (List.range (8 / 2 - 1)).foldl
    (fun s r => applyMatrix noirM (addC (sigma s) (rc3 (3 * (r + 1))))) s
  let s := applyMatrix noirP (addC (sigma s) (rc3 (3 * (8 / 2))))
  let s := (List.range 57).foldl partialStep s
  let s := (List.range (8 / 2 - 1)).foldl
    (fun s r => applyMatrix noirM (addC (sigma s) (rc3 ((8 / 2 + 1) * 3 + 57 + r * 3)))) s
  applyMatrix noirM (sigma s)

-- hash_internal: state = [0, input[0], input[1]]; output perm(state)[0]
def noirHash2 (a b : K) : K := (noirPermute (0, a, b)).1

/-- The same permutation cut into 65 rounds (README, "The round cut"); `noirPermute_eq_fold`
proves the relation. -/
def noirRound (j : ℕ) (s : St) : St :=
  if j < 3 then applyMatrix noirM (addC (sigma s) (rc3 (3 * (j + 1))))
  else if j = 3 then applyMatrix noirP (addC (sigma s) (rc3 12))
  else if j < 61 then partialStep s (j - 4)
  else if j < 64 then applyMatrix noirM (addC (sigma s) (rc3 (72 + 3 * (j - 61))))
  else applyMatrix noirM (sigma s)
"""


def wit_block(Tw, vw):
    tl = "[" + ",\n  ".join(m3(Tw[j]) for j in range(4, 62)) + "]"
    vl = "[" + ",\n  ".join(st(vw[j]) for j in range(4, 61)) + "]"
    return f"""-- WIT: untrusted witnesses (scripts/common.py, `witnesses`). Every use is kernel-checked.
-- Tw j = A'_(j-4) (the backward factorization, README "The round cut"), j = 4..61 (Tw 61 = I);
-- vw j, j = 4..60.
def TwL : List M3 :=
  {tl}

def Tw (j : ℕ) : M3 := TwL.getD (j - 4) I3

def vwL : List St :=
  {vl}

def vw (j : ℕ) : St := vwL.getD (j - 4) 0

/-- boundary map before round j (README, "The round cut") -/
def L (j : ℕ) (x : St) : St :=
  if 4 ≤ j ∧ j ≤ 60 then aff (Tw j) (vw j) x else if j = 65 then x else x + plainC j
"""


