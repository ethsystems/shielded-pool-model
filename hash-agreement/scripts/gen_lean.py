COMPOSE = """-- COMPOSE
/-- The loop-shaped transcription equals the 65-round cut. After the prologue check, both sides
unfold to the same round sequence (definitional, checked by `rfl`). -/
theorem noirPermute_eq_fold (s : St) :
    noirPermute s = (List.range 65).foldl (fun s j => noirRound j s) (L 0 s) := by
  have h0 : L 0 s = addC s (rc3 0) := by
    rw [L_full (j := 0) (by omega), show plainC 0 = rc3 0 by decide +kernel]
    rfl
  have e1 : ∀ s : St, (List.range (8 / 2 - 1)).foldl
      (fun s r => applyMatrix noirM (addC (sigma s) (rc3 (3 * (r + 1))))) s =
      (List.range 3).foldl (fun s j => noirRound j s) s := fun s =>
    List.foldl_ext _ _ _ (fun s r hr => (noirRound_first (List.mem_range.1 hr) s).symm)
  have e2 : ∀ s : St, (List.range 57).foldl partialStep s =
      (List.range 57).foldl (fun s i => noirRound (4 + i) s) s := by
    intro s
    refine List.foldl_ext _ _ _ (fun s i hi => ?_)
    have hi' := List.mem_range.1 hi
    rw [noirRound_partial (j := 4 + i) (by omega) (by omega), show 4 + i - 4 = i by omega]
  have e3 : ∀ s : St, (List.range (8 / 2 - 1)).foldl
      (fun s r => applyMatrix noirM (addC (sigma s) (rc3 ((8 / 2 + 1) * 3 + 57 + r * 3)))) s =
      (List.range 3).foldl (fun s i => noirRound (61 + i) s) s := by
    intro s
    refine List.foldl_ext _ _ _ (fun s i hi => ?_)
    have hi' := List.mem_range.1 hi
    rw [noirRound_second (j := 61 + i) (by omega) (by omega),
      show (8 / 2 + 1) * 3 + 57 + i * 3 = 72 + 3 * (61 + i - 61) by omega]
  have split : List.range 65 = List.range 3 ++ [3] ++ (List.range 57).map (fun i => 4 + i) ++
      (List.range 3).map (fun i => 61 + i) ++ [64] := by decide
  rw [h0, split, List.foldl_append, List.foldl_append, List.foldl_append, List.foldl_append,
    List.foldl_map, List.foldl_map, List.foldl_cons, List.foldl_nil, List.foldl_cons, List.foldl_nil]
  try beta_reduce
  rw [← e1, ← e2, ← e3, noirRound_three, noirRound_last]
  unfold noirPermute
  rfl

theorem perm_eq_of_rounds
    (h : ∀ j < 65, ∀ x, noirRound j (L j x) = L (j + 1) (plainRound j x)) :
    ∀ s, noirPermute s = plainPerm s := by
  intro s
  have key : ∀ n, n ≤ 65 → (List.range n).foldl (fun s j => noirRound j s) (L 0 s) =
      L n ((List.range n).foldl (fun s j => plainRound j s) s) := by
    intro n hn
    induction n with
    | zero => rfl
    | succ n ih =>
      rw [List.range_succ, List.foldl_append, List.foldl_append, List.foldl_cons, List.foldl_nil,
        List.foldl_cons, List.foldl_nil]
      try beta_reduce
      rw [ih (by omega), h n (by omega)]
  rw [noirPermute_eq_fold, plainPerm, key 65 le_rfl, L_65]
"""

D = "(by decide +kernel)"


def inst(j, name=None):
    """Round lemma j: the generic identity instantiated, every numeric hypothesis kernel-checked."""
    name = name or f"round{j}"
    stmt = f"theorem {name} (x : St) : noirRound {j} (L {j} x) = L {j + 1} (plainRound {j} x)"
    if j < 3:
        body = (f"  rw [L_full (j := {j}) (by omega), L_full (j := {j + 1}) (by omega), "
                f"noirRound_first (j := {j}) (by omega), plainRound_full (j := {j}) (by omega)]\n"
                f"  exact full_step x (plainC {j}) (plainC {j + 1}) (rc3 (3 * ({j} + 1))) noirM plainM {D} {D}")
    elif j == 3:
        body = (f"  rw [L_full (j := 3) (by omega), L_aff (j := 4) (by omega) (by omega), "
                f"noirRound_three, plainRound_full (j := 3) (by omega)]\n"
                f"  exact pre_step x (plainC 3) (rc3 12) (vw 4) noirP plainM (Tw 4) {D} {D}")
    elif j < 60:
        body = (f"  rw [L_aff (j := {j}) (by omega) (by omega), L_aff (j := {j + 1}) (by omega) (by omega), "
                f"noirRound_partial (j := {j}) (by omega) (by omega), plainRound_partial (j := {j}) (by omega) (by omega)]\n"
                f"  exact partial_step x (plainC {j}) (vw {j}) (vw {j + 1}) _ _ _ _ _ _ (Tw {j}) (Tw {j + 1}) plainM\n"
                f"    {D} {D} {D} {D}")
    elif j == 60:
        body = (f"  rw [L_aff (j := 60) (by omega) (by omega), L_full (j := 61) (by omega), "
                f"noirRound_partial (j := 60) (by omega) (by omega), plainRound_partial (j := 60) (by omega) (by omega)]\n"
                f"  exact (partial_step x (plainC 60) (vw 60) (plainC 61) _ _ _ _ _ _ (Tw 60) I3 plainM\n"
                f"    {D} {D} {D} {D}).trans (aff_I3 _ _)")
    elif j < 64:
        body = (f"  rw [L_full (j := {j}) (by omega), L_full (j := {j + 1}) (by omega), "
                f"noirRound_second (j := {j}) (by omega) (by omega), plainRound_full (j := {j}) (by omega)]\n"
                f"  exact full_step x (plainC {j}) (plainC {j + 1}) (rc3 (72 + 3 * ({j} - 61))) noirM plainM {D} {D}")
    else:
        body = (f"  rw [L_full (j := 64) (by omega), L_65, noirRound_last, plainRound_full (j := 64) (by omega)]\n"
                f"  exact last_step x (plainC 64) noirM plainM {D}")
    return f"{stmt} := by\n{body}\n"


NEG_STMT = ("theorem round4_wrong (x : St) :\n"
            "    partialBody (rc 15) (sp 5) (sp 6) (sp 7) (sp 8) (sp 9) (L 4 x) = L 5 (plainRound 4 x)")
NEG_PROP = "∀ x : St, partialBody (rc 15) (sp 5) (sp 6) (sp 7) (sp 8) (sp 9) (L 4 x) = L 5 (plainRound 4 x)"


def neg_control():
    """round4 with the sparse factor of round 5 (indices 5..9) at round 4. Same proof text after unfold."""
    body = ("  rw [L_aff (j := 4) (by omega) (by omega), L_aff (j := 5) (by omega) (by omega), "
            "plainRound_partial (j := 4) (by omega) (by omega)]\n"
            "  exact partial_step x (plainC 4) (vw 4) (vw 5) _ _ _ _ _ _ (Tw 4) (Tw 5) plainM\n"
            f"    {D} {D} {D} {D}")
    return f"{NEG_STMT} := by\n{body}\n"


def mode_d(j, Cp, M, rc, sp, Tw, vw):
    """Direct expansion: substitute the numerals, expand, reduce coefficients mod F."""
    r = j - 4 if 4 <= j <= 60 else None
    lines = [f"theorem round{j}D (x : St) : noirRound {j} (L {j} x) = L {j + 1} (plainRound {j} x) := by"]
    if j == 3:
        lines.append("  rw [L_full (j := 3) (by omega), L_aff (j := 4) (by omega) (by omega), noirRound_three, plainRound_full (j := 3) (by omega)]")
        tabs = [("rc3 12", st([rc[12], rc[13], rc[14]])), ("plainC 3", st(Cp[9:12])), ("vw 4", st(vw[4])),
                ("noirP", None), ("plainM", None), ("Tw 4", m3(Tw[4]))]
    else:
        tgt = f"L_aff (j := {j + 1}) (by omega) (by omega)" if j < 60 else "L_full (j := 61) (by omega)"
        lines.append(f"  rw [L_aff (j := {j}) (by omega) (by omega), {tgt}, noirRound_partial (j := {j}) (by omega) (by omega), plainRound_partial (j := {j}) (by omega) (by omega)]")
        lines.append("  rw [partialStep]")
        tabs = [(f"rc ((8 / 2 + 1) * 3 + ({j} - 4))", k(rc[15 + r]))]
        for i, idx in enumerate([0, 1, 2, "3 + 1 - 1", "3 + 2 - 1"]):
            tabs.append((f"sp ((3 * 2 - 1) * ({j} - 4) + {idx})", k(sp[5 * r + i])))
        tabs += [(f"plainC {j}", st(Cp[3 * j:3 * j + 3])), (f"vw {j}", st(vw[j])), (f"Tw {j}", m3(Tw[j])), ("plainM", None)]
        if j < 60:
            tabs += [(f"vw {j + 1}", st(vw[j + 1])), (f"Tw {j + 1}", m3(Tw[j + 1]))]
        else:
            tabs += [("plainC 61", st(Cp[183:186]))]
    hs = []
    for n, (lhs, val) in enumerate(tabs):
        if val is None:
            continue
        lines.append(f"  have h{n} : {lhs} = {val} := by decide +kernel")
        hs.append(f"h{n}")
    lines.append(f"  rw [{', '.join(hs)}]")
    lines.append("  obtain ⟨x0, x1, x2⟩ := x")
    unf = "partialBody, " if j != 3 else "applyMatrix, addC, sigma, sboxAll, "
    lines.append(f"  simp only [{unf}aff, vm, pmix, sbox0, plainM, noirP, Prod.mk_add_mk, Prod.mk.injEq]")
    lines.append("  have hc : CharP K F := ZMod.charP F")
    lines.append("  refine ⟨?_, ?_, ?_⟩ <;> (rw [← sub_eq_zero]; ring_nf; reduce_mod_char!)")
    return "\n".join(lines) + "\n"


SOLM = ", ".join(f"SolM{i}{j}" for i in range(3) for j in range(3))


def sol_rounds(C):
    """Each Solidity segment against plainRound; boundary map x + c_j (no basis change)."""
    lit = lambda j: st(C[3 * j:3 * j + 3])
    out = []
    out.append(f"""theorem solR0_eq (a b : K) : solR0 a b = plainRound 0 (0, a, b) + plainC 1 := by
  rw [plainRound_full (j := 0) (by omega), show plainC 0 = {lit(0)} by decide +kernel,
    show plainC 1 = {lit(1)} by decide +kernel]
  simp only [solR0, {SOLM}, plainM, pmix, sboxAll, Prod.mk_add_mk, Prod.mk.injEq]
  have hc : CharP K F := ZMod.charP F
  refine ⟨?_, ?_, ?_⟩ <;> (rw [← sub_eq_zero]; ring_nf; reduce_mod_char!)
""")
    for j in range(1, 64):
        full = j < 4 or j >= 61
        unf = f"plainRound_full (j := {j}) (by omega)" if full else f"plainRound_partial (j := {j}) (by omega) (by omega)"
        out.append(f"""theorem solR{j}_eq (x : St) : solR{j} (x + plainC {j}) = plainRound {j} x + plainC {j + 1} := by
  rw [{unf}, show plainC {j} = {lit(j)} by decide +kernel,
    show plainC {j + 1} = {lit(j + 1)} by decide +kernel]
  obtain ⟨x0, x1, x2⟩ := x
  simp only [solR{j}, {SOLM}, plainM, pmix, sboxAll, sbox0, Prod.mk_add_mk, Prod.mk.injEq]
  refine ⟨?_, ?_, ?_⟩ <;> ring
""")
    out.append(f"""theorem solLast_eq (x : St) : solLast (x + plainC 64) = (plainRound 64 x).1 := by
  rw [plainRound_full (j := 64) (by omega), show plainC 64 = {lit(64)} by decide +kernel]
  obtain ⟨x0, x1, x2⟩ := x
  simp only [solLast, {SOLM}, plainM, pmix, sboxAll, Prod.mk_add_mk]
  ring
""")
    rws = ", ".join(["solR0_eq"] + [f"solR{j}_eq" for j in range(1, 64)] + ["solLast_eq"])
    out.append(f"""set_option maxHeartbeats 2000000 in
theorem solHashSeg_eq_plainHash2 (a b : K) : solHashSeg a b = plainHash2 a b := by
  unfold solHashSeg
  rw [{rws}]
  rw [plainHash2, plainPerm, show List.range 65 = {list(range(65))} by decide]
  simp only [List.foldl_cons, List.foldl_nil]

theorem solHashSeg_eq_noirHash2 (a b : K) : solHashSeg a b = noirHash2 a b := by
  rw [solHashSeg_eq_plainHash2, noirHash2_eq_plainHash2]
""")
    return "\n".join(out)


def vectors_block(vectors):
    rows = ",\n  ".join(f"({a}, {b}, {o})" for a, b, o in vectors)
    return f"""/-- (a, b, PoseidonT3.hash([a, b])): inputs/vectors/inputs.json and sol_outputs.txt. -/
def vectors : List (K × K × K) :=
  [{rows}]

/-- how many of the 300 vectors `f` reproduces (compiled evaluation: a test, not a proof) -/
def agree (f : K → K → K) : ℕ := (vectors.filter (fun v => f v.1 v.2.1 == v.2.2)).length

-- expect (300, 300, 300, 300)
#eval (agree solHash, agree solHashSeg, agree plainHash2, agree noirHash2)
"""


