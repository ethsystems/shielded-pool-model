def k(n):
    return str(n % c.F)


def m3(A):
    return "⟨" + ", ".join(k(A[i][j]) for i in range(3) for j in range(3)) + "⟩"


def st(v):
    return f"({k(v[0])}, {k(v[1])}, {k(v[2])})"


def klist(xs):
    return "[" + ",\n  ".join(k(x) for x in xs) + "]"


