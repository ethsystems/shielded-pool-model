#!/usr/bin/env python3
"""Compile every control and compare the result with controls/EXPECTED.tsv.

  controls.py [--target T] [--jobs N]           check every control against EXPECTED.tsv
  controls.py [--target T] [--jobs N] --write   write EXPECTED.tsv from this run (after review)

Targets (scripts/targets.py): `main` (controls/) and `fold-bridge` (fold-bridge/controls/),
default `main`. The controls of a target are <dir>/*.lean (written by hand) and <dir>/gen/*.lean
(generated by scripts/gen-controls.py, which must reproduce them). A `fail` control must fail to compile,
with exactly the first error of EXPECTED.tsv (line, column and the start of the message); a
parse error or an unknown constant, namespace or module never counts. A `pass` control must
compile with no `sorry`, and its `#print axioms` lines must list only `propext`,
`Classical.choice` and `Quot.sound`. Logs go to build/controls/.
"""
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from targets import PKG, target  # noqa: E402

BROKEN = re.compile(r'unexpected token|unknown constant|unknown namespace|unknown module')
ALLOWED = {'propext', 'Classical.choice', 'Quot.sound'}


def controls(t):
    ctl = t.controls
    return {f.stem: f.relative_to(t.cwd) for f in sorted(ctl.glob('*.lean')) + sorted((ctl / 'gen').glob('*.lean'))}


def first_error(text):
    for line in text.splitlines():
        m = re.match(r'^(?:\S*/)?controls/(?:gen/)?[^:/]+\.lean:(\d+):(\d+): error(?:\([^)]*\))?: (.*)$', line)
        if m:
            return f'{m.group(1)}:{m.group(2)}: {m.group(3)[:100]}'
    return ''


def run(t, logs, item):
    name, rel = item
    argv, env = t.lean(str(rel))
    p = subprocess.run(argv, cwd=t.cwd, env=env, capture_output=True, text=True)
    out = p.stdout + p.stderr
    (logs / f'{name}.log').write_text(out)
    return name, p.returncode, out


def main():
    args = sys.argv[1:]
    jobs, tname = 1, 'main'
    while args[:1] in (['--jobs'], ['--target']):
        if args[0] == '--jobs':
            jobs = int(args[1])
        else:
            tname = args[1]
        args = args[2:]
    write = args == ['--write']
    t = target(tname)
    EXP = t.controls / 'EXPECTED.tsv'
    LOGS = PKG / 'build' / 'controls' / tname
    bad = []
    g = subprocess.run([sys.executable, str(PKG / 'scripts' / 'gen-controls.py'), '--check'],
                       capture_output=True, text=True)
    if g.returncode != 0:
        bad.append((g.stdout + g.stderr).strip())
    ctl = controls(t)
    for n in ctl:
        if not (n.startswith('pass_') or n.startswith('fail_')):
            bad.append(f'{n}: a control name starts with pass_ or fail_')
    expected = {}
    if not write:
        for l in EXP.read_text().splitlines():
            if l and not l.startswith('#'):
                n, v, e = (l.split('\t') + [''])[:3]
                expected[n] = (v, e)
        for n in sorted(set(expected) ^ set(ctl)):
            bad.append(f'{n}: in only one of EXPECTED.tsv and controls/')
    LOGS.mkdir(parents=True, exist_ok=True)
    rows = []
    with ThreadPoolExecutor(jobs) as ex:
        for name, ec, out in ex.map(lambda it: run(t, LOGS, it), list(ctl.items())):
            v = 'pass' if name.startswith('pass_') else 'fail'
            err = first_error(out)
            if v == 'pass':
                if ec != 0:
                    bad.append(f'{name}: must compile, failed: {err}')
                if re.search(r'declaration uses .sorry', out):
                    bad.append(f'{name}: uses sorry')
                lines = re.findall(r"depends on axioms: \[([^\]]*)\]|does not depend on any axioms", out)
                if not lines:
                    bad.append(f'{name}: no #print axioms output')
                for axs in lines:
                    s = {a.strip() for a in axs.split(',') if a.strip()}
                    if s - ALLOWED:
                        bad.append(f'{name}: axioms {sorted(s)}')
                err = ''
            else:
                if ec == 0:
                    bad.append(f'{name}: must fail, compiled')
                elif not err or BROKEN.search(err):
                    bad.append(f'{name}: broken control (no error line, parse or name error): {err}')
            if not write and name in expected and expected[name] != (v, err):
                bad.append(f'{name}: result {v} {err!r} differs from EXPECTED.tsv {expected[name]}')
            rows.append((name, v, err))
            print(f'{v} exit={ec} {name} {err}', flush=True)
    if write:
        EXP.write_text('# control\tverdict\tfirst error (line:col: start of the message), for fail controls\n'
                       + ''.join(f'{n}\t{v}\t{e}\n' for n, v, e in sorted(rows)))
    if bad:
        for b in bad:
            print('CONTROL', b)
        print(f'CONTROLS FAIL ({tname}): {len(bad)} problems in {len(rows)} controls')
        sys.exit(1)
    npass = sum(1 for r in rows if r[1] == 'pass')
    print(f'CONTROLS PASS ({tname}): {len(rows) - npass} must-fail controls fail as recorded, {npass} must-pass controls compile')


if __name__ == '__main__':
    main()
