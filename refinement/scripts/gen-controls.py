#!/usr/bin/env python3
"""Generate the mutation controls (controls/gen/ and fold-bridge/controls/gen/).

  gen-controls.py           write both directories from the modules they copy
  gen-controls.py --check   check that both directories equal the generator output

Each `fail_*` control is a copy of one module with one definition or statement changed and every
proof unchanged; it must fail to compile (the EXPECTED.tsv beside it). Each `pass_*` copy has no
change (plus `#print axioms` lines for its main theorems) and must compile, so a failure of the
others comes from the change. The LeanIMT copies import only what Tree/LeanImt.lean imports, so
they do not clash with it; the fold-bridge copies rename the namespace `FoldBridge`.
"""
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent

IMT = PKG / 'Tree' / 'LeanImt.lean'
IMT_AXIOMS = ['rootOf_eq_sub', 'complete', 'complete_mem', 'binding', 'binding_mem_or_bad',
              'treeLink']
IMT_MUTANTS = {
    'pass_imt_unchanged': (None, 'no change'),
    'fail_imt_fold_direction_flipped': (
        ('if indices.getD i false then H (path.getD i 0) node else H node (path.getD i 0)',
         'if indices.getD i false then H node (path.getD i 0) else H (path.getD i 0) node'),
        'the circuit fold `level` puts the node on the other side of each sibling'),
    'fail_imt_no_carry': (
        ('    if M.length ≤ 2 ^ l then sub H l M\n', '    if False then sub H l M\n'),
        'the LeanIMT root `sub` never carries a node without a right sibling up'),
    'fail_imt_proof_left_bit_true': (
        ('[(false, sub H l (M.drop (2 ^ l)))]', '[(true, sub H l (M.drop (2 ^ l)))]'),
        'the compressed proof gives a left child the direction bit of a right child'),
}

BRIDGE = PKG / 'fold-bridge' / 'FoldBridge' / 'Bridge.lean'
BRIDGE_AXIOMS = ['merkleRoot_val', 'complete_field', 'binding_mem_or_bad_field', 'bad_field']
_B = ('      LeanImt.merkleRoot (Hn h) leaf.val depth.toNat indices (path.map (·.val)) := by\n'
      '  rw [← merkleRoot_cast, map_val_cast]')
BRIDGE_MUTANTS = {
    'pass_bridge_unchanged': (None, 'no change'),
    'fail_bridge_direction_flipped': (
        (_B, _B.replace('LeanImt.merkleRoot (Hn h)', 'LeanImt.merkleRoot (fun a b => Hn h b a)')),
        '`merkleRoot_val` with the inputs of the word hash swapped'),
    'fail_bridge_depth_plus_one': (
        (_B, _B.replace('depth.toNat indices', '(depth.toNat + 1) indices')),
        '`merkleRoot_val` with the `Nat` depth one larger'),
    'fail_bridge_bad_field_no_range': (
        ('theorem bad_field (h : Fp p → Fp p → Fp p) (L : List ℕ) (hL : ∀ x ∈ L, x < p.natVal)\n',
         'theorem bad_field (h : Fp p → Fp p → Fp p) (L : List ℕ)\n'),
        '`bad_field` without the range premise (every leaf below the field modulus)'),
}

SETS = [
    (IMT, 'Tree/LeanImt.lean', PKG / 'controls' / 'gen', IMT_MUTANTS,
     lambda n: '\n' + ''.join(f'#print axioms LeanShieldedPool.Refine.LeanImt.{t}\n' for t in IMT_AXIOMS),
     lambda text, n: text),
    (BRIDGE, 'fold-bridge/FoldBridge/Bridge.lean', PKG / 'fold-bridge' / 'controls' / 'gen',
     BRIDGE_MUTANTS,
     lambda n: '\n' + ''.join(f'#print axioms FoldBridgeControl_{n}.{t}\n' for t in BRIDGE_AXIOMS),
     lambda text, n: text.replace('namespace FoldBridge\n', f'namespace FoldBridgeControl_{n}\n')
                         .replace('end FoldBridge\n', f'end FoldBridgeControl_{n}\n')),
]


def generate():
    out = {}
    for src, rel, outdir, mutants, axioms, rename in SETS:
        text0 = src.read_text()
        for name, (m, what) in mutants.items():
            text = text0
            if m is not None:
                a, b = m
                assert text0.count(a) == 1, name
                text = text0.replace(a, b)
            text = rename(text, name)
            if m is None:
                text += axioms(name)
            head = f'-- Control {name}, generated by scripts/gen-controls.py from {rel}:\n-- {what}.\n'
            out[outdir / f'{name}.lean'] = head + text
    return out


def main():
    files = generate()
    dirs = {p.parent for p in files}
    if sys.argv[1:] == ['--check']:
        have = {p for d in dirs for p in d.glob('*.lean')}
        bad = sorted(str(p.relative_to(PKG)) for p in have ^ set(files))
        bad += sorted(str(p.relative_to(PKG)) for p in files if p in have and p.read_text() != files[p])
        if bad:
            sys.exit(f'generated controls differ from gen-controls.py output: {bad}')
        print(f'generated controls: {len(files)} files equal the generator output')
        return
    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)
    for p, t in files.items():
        p.write_text(t)
    print(f'wrote {len(files)} generated controls')


if __name__ == '__main__':
    main()
