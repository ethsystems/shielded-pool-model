#!/usr/bin/env python3
"""Run Census.lean and check its output against statements/.

  census.py [--target T]           compare with the inventory and raw-type pins of target T
  census.py [--target T] --write   write those two files from the census (after a review)

Targets (scripts/targets.py): `main` (Census.lean; statements/INVENTORY.md and
statements/RAW.sha256) and `fold-bridge` (fold-bridge/Census.lean; statements/FOLD-BRIDGE.md and
statements/FOLD-BRIDGE.sha256). Default `main`.

Checks: the census imports every module of the package; no package module declares an axiom or
an opaque constant; every theorem (auxiliary ones included) depends on a subset of `propext`,
`Classical.choice` and `Quot.sound`; no type holds a syntax value or an elided term; and the
non-auxiliary theorems are exactly those of statements/INVENTORY.md, with the same printed
statement and the same SHA-256 of the raw type (statements/RAW.sha256).
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from targets import target  # noqa: E402

ALLOWED = {'propext', 'Classical.choice', 'Quot.sound'}
HEADER = """# {title}
# Generated by scripts/census.py --write from the census (Census.lean); checked by scripts/check.sh.
# Format (one per line): <fully qualified name> :: <statement as Lean prints it; line breaks of the
# printer, with their indentation, become one space>
# Grouped by module. Auxiliary theorems (internal or private names) are left out; the census
# still checks their axioms. statements/RAW.sha256 pins the SHA-256 of the raw form of each type.
"""


def package_modules(t):
    return {'.'.join(f.relative_to(t.cwd).with_suffix('').parts)
            for g in t.groups for f in (t.cwd / g).rglob('*.lean')}


def main():
    args = sys.argv[1:]
    name = 'main'
    if args[:1] == ['--target']:
        name, args = args[1], args[2:]
    write = args == ['--write']
    t = target(name)
    INV, RAW = t.inventory, t.raw
    argv, env = t.lean(t.census)
    p = subprocess.run(argv, cwd=t.cwd, env=env, capture_output=True, text=True)
    if p.returncode != 0:
        print(p.stdout[-3000:], p.stderr[-3000:])
        sys.exit('CENSUS FAIL: Census.lean did not run')
    rows = [json.loads(l) for l in p.stdout.splitlines() if l.startswith('{')]
    bad = []
    seen = {r['module'] for r in rows if r['kind'] == 'module'}
    missing = package_modules(t) - seen
    if missing:
        bad.append(f'modules not imported by the census: {sorted(missing)}')
    thms = [r for r in rows if r['kind'] == 'theorem']
    for r in rows:
        if r['kind'] in ('axiomInfo', 'opaqueInfo'):
            bad.append(f"{r['kind']} {r['name']} in {r['module']}")
    for r in thms:
        if set(r['axioms']) - ALLOWED:
            bad.append(f"axioms of {r['name']}: {r['axioms']}")
        if '(dsyntax)' in r['raw']:
            bad.append(f"syntax value in the type of {r['name']}")
        if '⋯' in r['type']:
            bad.append(f"elided statement of {r['name']}")
    public = sorted((r for r in thms if not r['internal']), key=lambda r: (r['module'], r['name']))
    lines, mod = [], None
    for r in public:
        if r['module'] != mod:
            mod = r['module']
            lines.append(f'# {mod}')
        flat = ' '.join(x.strip() for x in r['type'].splitlines())
        lines.append(f"{r['name']} :: {flat}")
    texts = {INV: HEADER.format(title=t.title) + '\n'.join(lines) + '\n'}
    raw_lines = [f"{hashlib.sha256(r['raw'].encode()).hexdigest()}  {r['name']}" for r in public]
    texts[RAW] = '\n'.join(sorted(raw_lines, key=lambda l: l.split()[1])) + '\n'
    if write:
        INV.parent.mkdir(exist_ok=True)
        for path, text in texts.items():
            path.write_text(text)
        print(f'wrote {INV.name} and {RAW.name} ({len(public)} theorems)')
    else:
        def entries(text, sep):
            d = {}
            for l in text.splitlines():
                if l and not l.startswith('#'):
                    a, b = (l.split(sep, 1) if sep == ' :: ' else reversed(l.split('  ', 1)))
                    if a in d:
                        bad.append(f'duplicate entry {a}')
                    d[a] = b
            return d
        for path in (INV, RAW):
            sep = '  ' if path == RAW else ' :: '
            want, got = entries(path.read_text(), sep), entries(texts[path], sep)
            for n in sorted(want.keys() - got.keys()):
                bad.append(f'{path.name}: missing theorem {n}')
            for n in sorted(got.keys() - want.keys()):
                bad.append(f'{path.name}: theorem not listed: {n}')
            for n in sorted(want.keys() & got.keys()):
                if want[n] != got[n]:
                    bad.append(f'{path.name}: entry of {n} differs')
    nax = sum(1 for r in thms if r['axioms'])
    if bad:
        for b in bad[:40]:
            print('CENSUS', b)
        print(f'CENSUS FAIL: {len(bad)} problems')
        sys.exit(1)
    print(f'CENSUS PASS ({name}): {len(seen)} modules, {len(thms)} theorems ({len(public)} in the inventory), '
          f'{nax} with axioms, all within {sorted(ALLOWED)}')


if __name__ == '__main__':
    main()
